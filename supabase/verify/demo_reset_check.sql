-- demo_reset_check.sql
-- Live check for private.reset_demo() (migration 0007_demo_mode.sql).
-- Paste the whole file into the Supabase SQL Editor and click Run.
--
-- It runs private.reset_demo() twice and returns ONE row of four booleans:
--   idempotent        demo-org row counts per table are the same after the
--                     first and the second reset (and the seed is not empty)
--   others_untouched  row count and row-content hash of every table, outside
--                     the demo org, are identical before and after both resets
--                     (auth.users: every user except the two demo logins)
--   shifts_in_window  every demo shift starts in [w0, w0 + 14) (America/Regina)
--   gap_present       week w0 + 7 has the planned shortfall: Riverside has a
--                     Line Cook on Thursday morning but none for the evening,
--                     while the same Thursday in week w0 is covered
-- Expected: all four true.
--
-- Safety: the only writes are the two reset_demo() calls (demo org only) and
-- session temp tables. No non-demo row is modified.
-- The checks run in one REPEATABLE READ transaction so concurrent app traffic
-- cannot change the "before" and "after" snapshots. If it ever fails with
-- "could not serialize access", just run it again.

BEGIN ISOLATION LEVEL REPEATABLE READ;

DROP TABLE IF EXISTS pg_temp.demo_check_counts;
DROP TABLE IF EXISTS pg_temp.demo_check_result;
DROP VIEW IF EXISTS pg_temp.demo_check_snapshot;

-- One row per (scope, table): scope 'demo' counts demo-org rows,
-- scope 'other' counts and hashes every row outside the demo org.
CREATE TEMP VIEW demo_check_snapshot AS
WITH demo AS (
  SELECT 'd3e00000-0000-4000-8000-000000000001'::uuid AS org_id,
         'b0274d86-5ba5-439a-9e08-d69161dfd56d'::uuid AS manager_id,
         'a840a06a-eb99-43e6-94a5-78e5dc49ba98'::uuid AS employee_user_id
)
-- ---- demo org: counts only (ids are regenerated by every reset) ----
SELECT 'demo' AS scope, 'organizations' AS tbl, count(*) AS n, NULL::text AS h
  FROM public.organizations t, demo WHERE t.id = demo.org_id
UNION ALL SELECT 'demo', 'managers', count(*), NULL
  FROM public.managers t, demo WHERE t.organization_id = demo.org_id
UNION ALL SELECT 'demo', 'locations', count(*), NULL
  FROM public.locations t, demo WHERE t.organization_id = demo.org_id
UNION ALL SELECT 'demo', 'roles', count(*), NULL
  FROM public.roles t, demo WHERE t.organization_id = demo.org_id
UNION ALL SELECT 'demo', 'employees', count(*), NULL
  FROM public.employees t, demo WHERE t.organization_id = demo.org_id
UNION ALL SELECT 'demo', 'employee_roles', count(*), NULL
  FROM public.employee_roles t
  JOIN public.employees e ON e.id = t.employee_id, demo
  WHERE e.organization_id = demo.org_id
UNION ALL SELECT 'demo', 'employee_availability', count(*), NULL
  FROM public.employee_availability t, demo WHERE t.organization_id = demo.org_id
UNION ALL SELECT 'demo', 'employee_unavailability', count(*), NULL
  FROM public.employee_unavailability t, demo WHERE t.organization_id = demo.org_id
UNION ALL SELECT 'demo', 'coverage_requirements', count(*), NULL
  FROM public.coverage_requirements t
  JOIN public.locations l ON l.id = t.location_id, demo
  WHERE l.organization_id = demo.org_id
UNION ALL SELECT 'demo', 'schedules', count(*), NULL
  FROM public.schedules t, demo WHERE t.organization_id = demo.org_id
UNION ALL SELECT 'demo', 'shifts', count(*), NULL
  FROM public.shifts t, demo WHERE t.organization_id = demo.org_id
UNION ALL SELECT 'demo', 'time_off_requests', count(*), NULL
  FROM public.time_off_requests t, demo WHERE t.organization_id = demo.org_id
UNION ALL SELECT 'demo', 'shift_trade_requests', count(*), NULL
  FROM public.shift_trade_requests t, demo WHERE t.organization_id = demo.org_id
-- ---- everything else: count + hash of full row contents ----
UNION ALL SELECT 'other', 'organizations', count(*),
    md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), ''))
  FROM public.organizations t, demo WHERE t.id IS DISTINCT FROM demo.org_id
UNION ALL SELECT 'other', 'managers', count(*),
    md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), ''))
  FROM public.managers t, demo
  WHERE t.organization_id IS DISTINCT FROM demo.org_id AND t.id <> demo.manager_id
UNION ALL SELECT 'other', 'locations', count(*),
    md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), ''))
  FROM public.locations t, demo WHERE t.organization_id IS DISTINCT FROM demo.org_id
UNION ALL SELECT 'other', 'roles', count(*),
    md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), ''))
  FROM public.roles t, demo WHERE t.organization_id IS DISTINCT FROM demo.org_id
UNION ALL SELECT 'other', 'employees', count(*),
    md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), ''))
  FROM public.employees t, demo WHERE t.organization_id IS DISTINCT FROM demo.org_id
UNION ALL SELECT 'other', 'employee_roles', count(*),
    md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), ''))
  FROM public.employee_roles t
  JOIN public.employees e ON e.id = t.employee_id, demo
  WHERE e.organization_id IS DISTINCT FROM demo.org_id
UNION ALL SELECT 'other', 'employee_availability', count(*),
    md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), ''))
  FROM public.employee_availability t, demo WHERE t.organization_id IS DISTINCT FROM demo.org_id
UNION ALL SELECT 'other', 'employee_unavailability', count(*),
    md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), ''))
  FROM public.employee_unavailability t, demo WHERE t.organization_id IS DISTINCT FROM demo.org_id
UNION ALL SELECT 'other', 'coverage_requirements', count(*),
    md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), ''))
  FROM public.coverage_requirements t
  JOIN public.locations l ON l.id = t.location_id, demo
  WHERE l.organization_id IS DISTINCT FROM demo.org_id
UNION ALL SELECT 'other', 'schedules', count(*),
    md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), ''))
  FROM public.schedules t, demo WHERE t.organization_id IS DISTINCT FROM demo.org_id
UNION ALL SELECT 'other', 'shifts', count(*),
    md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), ''))
  FROM public.shifts t, demo WHERE t.organization_id IS DISTINCT FROM demo.org_id
UNION ALL SELECT 'other', 'time_off_requests', count(*),
    md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), ''))
  FROM public.time_off_requests t, demo WHERE t.organization_id IS DISTINCT FROM demo.org_id
UNION ALL SELECT 'other', 'shift_trade_requests', count(*),
    md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), ''))
  FROM public.shift_trade_requests t, demo WHERE t.organization_id IS DISTINCT FROM demo.org_id
-- auth.users: only the columns the reset could touch (sign-in timestamps on
-- real accounts are left out on purpose)
UNION ALL SELECT 'other', 'auth.users', count(*),
    md5(coalesce(string_agg(concat_ws(',', u.id, u.email, u.encrypted_password,
                                      u.email_confirmed_at, u.updated_at),
                            '|' ORDER BY u.id), ''))
  FROM auth.users u, demo
  WHERE u.id NOT IN (demo.manager_id, demo.employee_user_id);

CREATE TEMP TABLE demo_check_counts (
  phase text   NOT NULL,
  scope text   NOT NULL,
  tbl   text   NOT NULL,
  n     bigint NOT NULL,
  h     text
);

CREATE TEMP TABLE demo_check_result (
  idempotent       boolean,
  others_untouched boolean,
  shifts_in_window boolean,
  gap_present      boolean
);

INSERT INTO demo_check_counts SELECT 'before', scope, tbl, n, h FROM demo_check_snapshot;

SELECT private.reset_demo();
INSERT INTO demo_check_counts SELECT 'after1', scope, tbl, n, h FROM demo_check_snapshot;

SELECT private.reset_demo();
INSERT INTO demo_check_counts SELECT 'after2', scope, tbl, n, h FROM demo_check_snapshot;

INSERT INTO demo_check_result
WITH
demo AS (
  SELECT 'd3e00000-0000-4000-8000-000000000001'::uuid AS org_id,
         date_trunc('week', current_date)::date AS w0
),
riverside_line_cook_thu AS (
  -- Riverside Line Cook shifts on Thursday (w0 + 3 and w0 + 10), local time
  SELECT (s.start_datetime AT TIME ZONE 'America/Regina')::date AS local_day,
         s.start_datetime, s.end_datetime
  FROM public.shifts s
  JOIN public.locations l ON l.id = s.location_id
  JOIN public.roles r     ON r.id = s.role_id,
  demo
  WHERE s.organization_id = demo.org_id
    AND l.name = 'Riverside'
    AND r.name = 'Line Cook'
    AND (s.start_datetime AT TIME ZONE 'America/Regina')::date IN (demo.w0 + 3, demo.w0 + 10)
)
SELECT
  -- idempotent
  (SELECT bool_and(a.n = b.n)
     FROM demo_check_counts a
     JOIN demo_check_counts b ON b.scope = a.scope AND b.tbl = a.tbl AND b.phase = 'after2'
     WHERE a.phase = 'after1' AND a.scope = 'demo')
  AND (SELECT n > 0 FROM demo_check_counts
        WHERE phase = 'after2' AND scope = 'demo' AND tbl = 'shifts'),

  -- others_untouched
  (SELECT bool_and(a.n = b.n AND a.h = b.h AND a.n = c.n AND a.h = c.h)
     FROM demo_check_counts a
     JOIN demo_check_counts b ON b.scope = a.scope AND b.tbl = a.tbl AND b.phase = 'after1'
     JOIN demo_check_counts c ON c.scope = a.scope AND c.tbl = a.tbl AND c.phase = 'after2'
     WHERE a.phase = 'before' AND a.scope = 'other'),

  -- shifts_in_window
  (SELECT count(*) > 0
          AND bool_and(
            s.start_datetime >= (demo.w0::timestamp        AT TIME ZONE 'America/Regina')
            AND s.start_datetime < ((demo.w0 + 14)::timestamp AT TIME ZONE 'America/Regina'))
     FROM public.shifts s, demo
     WHERE s.organization_id = demo.org_id),

  -- gap_present: the w0 + 7 Thursday has the morning Line Cook but nothing
  -- covering the evening up to 21:00, while the w0 Thursday is covered
  (SELECT
       EXISTS (SELECT 1 FROM riverside_line_cook_thu t, demo
                WHERE t.local_day = demo.w0 + 10)
   AND NOT EXISTS (
         SELECT 1 FROM riverside_line_cook_thu t, demo
          WHERE t.local_day = demo.w0 + 10
            AND t.end_datetime >= ((demo.w0 + 10) + time '21:00') AT TIME ZONE 'America/Regina')
   AND EXISTS (
         SELECT 1 FROM riverside_line_cook_thu t, demo
          WHERE t.local_day = demo.w0 + 3
            AND t.end_datetime >= ((demo.w0 + 3) + time '21:00') AT TIME ZONE 'America/Regina'));

COMMIT;

SELECT idempotent, others_untouched, shifts_in_window, gap_present
FROM demo_check_result;
